import { mkdir, rm, writeFile } from 'node:fs/promises'
import { dirname, join, normalize, relative } from 'node:path'

const source = new URL('https://api.unsnow.org/')
const targetRoot = join(import.meta.dirname, '..', 'web', 'public')

async function fetchText(url) {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`${response.status} ${url}`)
  return response.text()
}

async function fetchAsset(url) {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`${response.status} ${url}`)
  return Buffer.from(await response.arrayBuffer())
}

function extractChunkAssets(bundle) {
  const jsRuntime = bundle.slice(bundle.indexOf('d.u=e=>'), bundle.indexOf('d.miniCssF='))
  const cssRuntime = bundle.slice(bundle.indexOf('d.miniCssF='), bundle.indexOf('d.g='))
  const jsAssets = [...jsRuntime.matchAll(/(\d+):"([a-f0-9]+)"/g)].map(
    ([, id, hash]) => `/static/js/async/${id}.${hash}.js`
  )
  const cssAssets = [...cssRuntime.matchAll(/(\d+):"([a-f0-9]+)"/g)].map(
    ([, id, hash]) => `/static/css/async/${id}.${hash}.css`
  )
  return [...jsAssets, ...cssAssets]
}

function toLocalPath(assetPath) {
  const localPath = normalize(join(targetRoot, assetPath.replace(/^\//, '')))
  if (relative(targetRoot, localPath).startsWith('..')) {
    throw new Error(`Unsafe asset path: ${assetPath}`)
  }
  return localPath
}

async function writeAsset(assetPath) {
  const url = new URL(assetPath, source)
  const localPath = toLocalPath(url.pathname)
  await mkdir(dirname(localPath), { recursive: true })
  await writeFile(localPath, await fetchAsset(url))
  return url.pathname
}

const html = await fetchText(source)
const entryMatch = html.match(/<script defer src="(\/static\/js\/index\.[^"]+\.js)"><\/script>/)
if (!entryMatch) throw new Error('Unable to locate the reference entry bundle')

const entryBundle = await fetchText(new URL(entryMatch[1], source))
const assets = new Set([
  '/favicon.ico',
  '/grok-mark.png',
  '/snowapi-theme/monochrome.css',
  '/snowapi-theme/unsnow-favicon.png',
  '/static/font/lora-latin-wght-normal.f60a385cfb.woff2',
  '/static/font/public-sans-latin-wght-normal.035c7fe496.woff2',
  ...[...html.matchAll(/(?:src|href)="(\/static\/(?:js|css)\/[^"]+)"/g)].map(([, path]) => path),
  ...extractChunkAssets(entryBundle),
])

await rm(join(targetRoot, 'static'), { recursive: true, force: true })
await rm(join(targetRoot, 'snowapi-theme'), { recursive: true, force: true })

const saved = await Promise.all([...assets].sort().map(writeAsset))
const localHtml = html
  .replace(/<script>\(function\(\)\{function c\(\)[\s\S]*?<\/script>/, '')
  .replace('</head>', '  <!-- Local mirror generated by scripts/sync-unsnow-mirror.mjs -->\n</head>')
await writeFile(join(targetRoot, 'index.html'), localHtml)

console.log(`Mirrored ${saved.length} reference assets to ${targetRoot}`)
